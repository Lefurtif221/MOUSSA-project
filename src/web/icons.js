// Fonction helper pour insérer une icône
function icon(name, size, color) {
  size = size || 20;
  color = color || 'currentColor';
  var svg = NdoketIcons[name] || '';
  if(svg){
    svg = svg.replace('width="24"', 'width="'+size+'"');
    svg = svg.replace('height="24"', 'height="'+size+'"');
    svg = svg.replace('stroke="currentColor"', 'stroke="'+color+'"');
    svg = svg.replace('fill="currentColor"', 'fill="'+color+'"');
  }
  return svg;
}

